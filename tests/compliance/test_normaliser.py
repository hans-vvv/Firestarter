class TestCompileRules:
    def test_exact_match(self):
        rules = _compile_rules(
            [{"match": "exact", "value": 'configure qos vlan-qos-policy "default"'}]
        )
        assert rules[0]('configure qos vlan-qos-policy "default"') is True
        assert rules[0]("configure qos vlan-qos-policy other") is False

    def test_startswith_match(self):
        rules = _compile_rules([{"match": "startswith", "value": "configure log filter"}])
        assert rules[0]("configure log filter 1001 entry 10") is True
        assert rules[0]("configure router bgp") is False

    def test_regex_match(self):
        rules = _compile_rules([{"match": "regex", "value": r"^configure port \d+/\d+/c\d+$"}])
        assert rules[0]("configure port 1/1/c1") is True
        assert rules[0]("configure port 1/1/c1 admin-state enable") is False

    def test_unknown_match_type_raises(self):
        with pytest.raises(ValueError, match="Unknown ignore rule match type"):
            _compile_rules([{"match": "contains", "value": "foo"}])

    def test_lambda_closure_captures_correct_value(self):
        rules = _compile_rules(
            [
                {"match": "exact", "value": "line-a"},
                {"match": "exact", "value": "line-b"},
            ]
        )
        assert rules[0]("line-a") is True
        assert rules[0]("line-b") is False
        assert rules[1]("line-b") is True
        assert rules[1]("line-a") is False

    def test_empty_rules_list_returns_empty(self):
        assert _compile_rules([]) == []


class TestCompileRedactRules:
    def test_redacts_matching_line(self):
        rules = _compile_redact_rules(
            [
                {
                    "match": "regex",
                    "value": r"^(configure system security user-params .* password) .*$",
                    "replace": r"\1 <redacted>",
                }
            ]
        )
        result = rules[0](
            "configure system security user-params local-user user admin password secret123"
        )
        assert (
            result
            == "configure system security user-params local-user user admin password <redacted>"
        )

    def test_non_matching_line_is_unchanged(self):
        rules = _compile_redact_rules(
            [
                {
                    "match": "regex",
                    "value": r"^(configure .* password) .*$",
                    "replace": r"\1 <redacted>",
                }
            ]
        )
        line = "configure router bgp neighbor 10.0.0.1"
        assert rules[0](line) == line

    def test_missing_replace_key_raises(self):
        with pytest.raises(ValueError, match="missing 'replace' key"):
            _compile_redact_rules([{"match": "regex", "value": r"^foo.*$"}])

    def test_empty_rules_list_returns_empty(self):
        assert _compile_redact_rules([]) == []


