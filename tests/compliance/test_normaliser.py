class TestUnwrapBraces:
    def test_unwraps_singleton_brace_line(self):
        assert _unwrap_braces('configure { system name "r1" }') == 'configure system name "r1"'

    def test_leaves_normal_line_unchanged(self):
        line = "configure router bgp"
        assert _unwrap_braces(line) == line

    def test_leaves_multiword_configure_without_braces_unchanged(self):
        line = "configure system security ssh"
        assert _unwrap_braces(line) == line

    def test_handles_inner_content_with_spaces(self):
        result = _unwrap_braces("configure { router isis 0 level-capability level-2 }")
        assert result == "configure router isis 0 level-capability level-2"


