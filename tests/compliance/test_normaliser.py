class TestNormaliseFormatTransforms:
    def test_strips_leading_whitespace(self, normaliser):
        result = normaliser.normalise(hostname="r1", raw="    configure router bgp\n")
        assert "configure router bgp" in result.lines

    def test_drops_empty_lines(self, normaliser):
        result = normaliser.normalise(hostname="r1", raw="\n\nconfigure router bgp\n\n")
        assert "" not in result.lines
        assert len(result.lines) == 1

    def test_drops_noise_comment_lines(self, normaliser):
        result = normaliser.normalise(
            hostname="r1", raw="# Generated by SR OS\nconfigure router bgp\n"
        )
        assert not any(line.startswith("#") for line in result.lines)
        assert "configure router bgp" in result.lines

    def test_strips_leading_slash(self, normaliser):
        result = normaliser.normalise(hostname="r1", raw="/configure router bgp\n")
        assert "configure router bgp" in result.lines
        assert "/configure router bgp" not in result.lines

    def test_unwraps_brace_singleton(self, normaliser):
        result = normaliser.normalise(hostname="r1", raw='configure { system name "r1" }\n')
        assert 'configure system name "r1"' in result.lines

    def test_result_hostname_matches_input(self, normaliser):
        result = normaliser.normalise(hostname="core1.tst-001", raw="configure router bgp\n")
        assert result.hostname == "core1.tst-001"

    def test_deduplicates_identical_lines(self, normaliser):
        result = normaliser.normalise(
            hostname="r1",
            raw="configure router bgp\nconfigure router bgp\n",
        )
        assert len(result.lines) == 1

    def test_drops_bare_slash_line(self, normaliser):
        # A stray "/" emitted by a template becomes "" after the leading-slash
        # strip and must NOT be injected into the rendered set (it would surface
        # as a phantom diff entry on every device that hits the bug).
        result = normaliser.normalise(
            hostname="r1",
            raw="/\nconfigure router bgp\n",
        )
        assert "" not in result.lines
        assert "configure router bgp" in result.lines

    def test_drops_brace_only_line_that_unwraps_to_empty(self, normaliser):
        # Defense in depth: any line that becomes empty after the format
        # transforms (slash-strip + brace-unwrap) is dropped, not added.
        result = normaliser.normalise(hostname="r1", raw="/\n")
        assert result.lines == frozenset()


