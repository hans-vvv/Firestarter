class TestLoadExtraLines:
    def test_returns_empty_when_no_files_exist(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        result = _load_extra_lines(role_name="core", hostname="r1")
        assert result == frozenset()

    def test_loads_role_file(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "core.cfg").write_text("configure router bgp\n/configure system name r1\n")
        result = _load_extra_lines(role_name="core", hostname="r1-unique")
        assert "configure router bgp" in result
        assert "configure system name r1" in result

    def test_loads_hostname_file(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "r1.cfg").write_text("configure router isis 0\n")
        result = _load_extra_lines(role_name="core", hostname="r1")
        assert "configure router isis 0" in result

    def test_unions_role_and_hostname_files(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "pe.cfg").write_text("shared-line\n")
        (tmp_path / "pe1.cfg").write_text("device-specific-line\n")
        result = _load_extra_lines(role_name="pe", hostname="pe1")
        assert "shared-line" in result
        assert "device-specific-line" in result

    def test_loads_base_file_for_any_device(self, tmp_path, monkeypatch):
        # base.cfg applies globally, regardless of role or hostname — the estate-wide
        # layer mirroring ignore/base.yaml.
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "base.cfg").write_text('configure system security ... user "admin"\n')
        result = _load_extra_lines(role_name="any-role", hostname="any-host")
        assert 'configure system security ... user "admin"' in result

    def test_unions_base_role_and_hostname_files(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "base.cfg").write_text("global-line\n")
        (tmp_path / "pe.cfg").write_text("role-line\n")
        (tmp_path / "pe1.cfg").write_text("host-line\n")
        result = _load_extra_lines(role_name="pe", hostname="pe1")
        assert {"global-line", "role-line", "host-line"} <= result

    def test_strips_leading_slash(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "core.cfg").write_text("/configure router bgp\n")
        result = _load_extra_lines(role_name="core", hostname="r-unique")
        assert "configure router bgp" in result

    def test_skips_comment_and_blank_lines(self, tmp_path, monkeypatch):
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "core.cfg").write_text("# comment\n\nconfigure router bgp\n")
        result = _load_extra_lines(role_name="core", hostname="r-unique")
        assert "# comment" not in result
        assert "" not in result
        assert "configure router bgp" in result

    def test_drops_bare_slash_line(self, tmp_path, monkeypatch):
        # A stray "/" in an extra .cfg becomes "" after the leading-slash strip
        # and must NOT be injected — symmetrical to the normalise() guard.
        monkeypatch.setattr("app.compliance.normaliser.EXTRA_DIR", tmp_path)
        (tmp_path / "core.cfg").write_text("/\nconfigure router bgp\n")
        result = _load_extra_lines(role_name="core", hostname="r-unique")
        assert "" not in result
        assert "configure router bgp" in result


