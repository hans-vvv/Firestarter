class TestRuleCaching:
    def test_rules_are_cached_per_hostname(self, normaliser):
        normaliser.normalise(hostname="r1", raw="configure router bgp\n")
        normaliser.normalise(hostname="r1", raw="configure router isis\n")
        assert "r1" in normaliser._rule_cache
        assert len(normaliser._rule_cache) == 1

    def test_different_hostnames_cached_separately(self, normaliser):
        normaliser.normalise(hostname="r1", raw="configure router bgp\n")
        normaliser.normalise(hostname="r2", raw="configure router bgp\n")
        assert "r1" in normaliser._rule_cache
        assert "r2" in normaliser._rule_cache
